"""Build planner-src/recipes.js from blocks-src/recipes.json (wiki recipe data gathered for the shopping list).

Run: python make_recipes_js.py   (from tools/blocks-src)
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, 'recipes.json'), encoding='utf-8'))

def short(r):
    out = {'s': r.get('station'), 'c': r.get('crafter'), 'i': [[x['item'], x['qty']] for x in r.get('inputs') or []], 'm': r.get('makes')}
    if not r.get('craftable', True):
        out['dig'] = 1
    notes = r.get('notes') or ''
    if '1.0 FLAG' in notes or 'SUSPICIOUS' in notes:
        out['flag'] = 1
    return out

recipes = {k: short(v) for k, v in d['recipes'].items() if v}
inter = {}
for k, v in d['intermediates'].items():
    if k.startswith('_') or not isinstance(v, dict) or not v.get('recipes'):
        continue
    r = v['recipes'][0]                                   # the first (main) recipe
    inter[k] = {'s': r.get('station'), 'c': r.get('crafter'), 'i': [[x['item'], x['qty']] for x in r.get('inputs') or []], 'm': r.get('makes')}
note = ("Counts are in 0.5 m blocks, about one item each (not documented; from 2024 player tests). "
        "Recipes are from the Enshrouded wiki, current to v0.9.0.3, so pre-1.0. 1.0 rebalanced many recipes "
        "and swapped stone for each biome's own stone, so check costs in game. Marked ⚠ where the wiki data looks off.")
js = ['// Recipes for the shopping list, from the Enshrouded wiki recipe table (pre-1.0, fetched ' + d.get('fetched', '') + ').',
      '// Generated by tools/blocks-src/make_recipes_js.py from recipes.json; do not edit by hand.',
      f'const PER_VOXEL = {d["per_voxel"].get("items_per_voxel") or 1};',
      'const RECIPE_NOTE = ' + json.dumps(note, ensure_ascii=False) + ';',
      'const RECIPES = ' + json.dumps(recipes, ensure_ascii=False, separators=(',', ':')) + ';',
      'const INTERMEDIATES = ' + json.dumps(inter, ensure_ascii=False, separators=(',', ':')) + ';', '']
out = os.path.join(HERE, '..', 'planner-src', 'recipes.js')
open(out, 'w', encoding='utf-8').write('\n'.join(js))
print(len(recipes), 'recipes,', len(inter), 'intermediates ->', os.path.getsize(out), 'bytes')

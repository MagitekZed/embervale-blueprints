"""Turn catalogue_colours.json into ../planner-src/blocks.js (the planner's block catalogue).

Pipeline (run in a scratch folder, see CLAUDE.md):
  1. Fetch Building_Materials, Roof_Materials, Terrain_Materials via the wiki API (action=parse).
  2. extract.py  -> names, groups, set/unlock text, icon URLs.
  3. Download the 100 px icons, then colours.py + finalize.py -> catalogue_colours.json.
  4. python make_blocks_js.py
"""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
items = json.load(open(os.path.join(here, 'catalogue_colours.json'), encoding='utf-8'))

GROUPS = {
    ('Building_Materials', 'Stone Blocks'): ('Stone blocks', 'wall'),
    ('Building_Materials', 'Wood Blocks'): ('Wood blocks', 'wall'),
    ('Building_Materials', 'Luminescent Blocks'): ('Luminescent blocks', 'wall'),
    ('Building_Materials', 'Other Blocks'): ('Other blocks', 'wall'),
    ('Roof_Materials', 'Roof Materials'): ('Roofs', 'wall'),
    ('Terrain_Materials', 'Road Blocks'): ('Terrain · roads', 'floor'),
    ('Terrain_Materials', 'Soil and Dirt'): ('Terrain · soil & dirt', 'floor'),
    ('Terrain_Materials', 'Terrain Materials'): ('Terrain · natural', 'floor'),
    ('Terrain_Materials', 'Rubble'): ('Terrain · rubble', 'floor'),
    ('Terrain_Materials', 'Other blocks'): ('Terrain · other', 'floor'),
}
clean = lambda t: (t or '').replace('�', '’').replace('  ', ' ').strip()
out = []
for it in items:
    g, kind = GROUPS[(it['page'], it['group'])]
    cells = [clean(c) for c in it.get('cells', [])]
    if it['page'] == 'Building_Materials':
        region, unlock = (cells + ['', ''])[:2]
    else:
        region, unlock = '', (cells[0] if cells else '')
    out.append({'n': clean(it['name']), 'g': g, 'k': kind, 'c': it['color'], 'r': region, 'u': unlock[:90]})

# the materials the wiki lacks (new in 1.0, the overgrowths), from colours_1_0.py
extra = os.path.join(here, 'catalogue_1_0.json')
if os.path.exists(extra):
    have = {b['n'] for b in out}
    out += [{k: e[k] for k in ('n', 'g', 'k', 'c', 'r', 'u')} for e in json.load(open(extra, encoding='utf-8')) if e['n'] not in have]
order = [v[0] for v in GROUPS.values()]
order[order.index('Roofs') + 1:order.index('Roofs') + 1] = ['Overgrowth']
out.sort(key=lambda b: (order.index(b['g']), b['n']))
js = ('// Block catalogue: every building block, roof and terrain material on the Enshrouded wiki\n'
      '// (Building_Materials, Roof_Materials, Terrain_Materials; wiki current to v0.9.0.3, fetched Oct 2026), plus the\n'
      '// ones new in 1.0 and the overgrowths, from enshrouded.tools (catalogue_1_0.json).\n'
      '// Colours are sampled from each block\'s icon (lit faces, lightly lifted), so they are close but not exact.\n'
      '// Generated by tools/blocks-src/make_blocks_js.py; do not edit by hand.\n'
      'const BLOCKS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('},{', '},\n  {') + ';\n')
open(os.path.join(here, '..', 'planner-src', 'blocks.js'), 'w', encoding='utf-8').write(js)
print(len(out), 'blocks;', len(js), 'bytes')
